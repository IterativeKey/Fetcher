#!/bin/sh
# Regenerates aria2.conf from env vars on every start (so .env changes always
# apply), and execs aria2c as the unprivileged user $PUID:$PGID.
#
# The download share is never chowned: it may hold files that aren't ours.
# $PUID:$PGID must already be able to write to it.

set -eu

CONF_DIR=/config
CONF=$CONF_DIR/aria2.conf
SESSION=$CONF_DIR/aria2.session

PUID=${PUID:-1000}
PGID=${PGID:-1000}
RPC_SECRET=${ARIA2_RPC_SECRET:?ARIA2_RPC_SECRET must be set}
RPC_PORT=${RPC_PORT:-6800}

case $RPC_SECRET in
  change-me|"") echo "ARIA2_RPC_SECRET is not configured (openssl rand -hex 16)" >&2; exit 1 ;;
esac

# /config is ours alone: fix only its own entries (non-recursive). Files are
# then written as $PUID:$PGID, so root needs CHOWN but not DAC_OVERRIDE.
mkdir -p "$CONF_DIR"
for f in "$CONF_DIR" "$CONF" "$SESSION"; do
  if [ -e "$f" ]; then chown "$PUID:$PGID" "$f"; fi
done
as_user() { su-exec "$PUID:$PGID" "$@"; }

if ! as_user sh -c 'f=/downloads/.fetcher-write-test; : > "$f" && rm -f "$f"' 2>/dev/null; then
  echo "/downloads is not writable by $PUID:$PGID - fix the share's permissions" \
       "or set PUID/PGID in .env to a NAS user that can write to it" >&2
  exit 1
fi

# umask 077 stays in this child shell; leaking it into aria2c would make
# every download 0600.
as_user sh -c 'umask 077; cat > "$1"' sh "$CONF" <<EOF
# Generated by fetcher's aria2 entrypoint on every start - edits are lost.
dir=/downloads
file-allocation=falloc
daemon=false
console-log-level=warn

# RPC (reachable only on the internal compose network)
enable-rpc=true
rpc-listen-all=true
rpc-listen-port=$RPC_PORT
rpc-secret=$RPC_SECRET
rpc-allow-origin-all=false

# Resume state: only unfinished jobs are saved. Saving finished ones
# (force-save) makes aria2 download them all again on every restart.
input-file=$SESSION
save-session=$SESSION
save-session-interval=30
force-save=false

# Never touch files that already exist: a name collision gets renamed to
# "name.1.ext" instead. Our own interrupted downloads still resume through
# their .aria2 control file; continue=true would instead treat any same-named
# file as a partial download of the new one and clobber it.
allow-overwrite=false
auto-file-renaming=true
continue=false
timeout=300
max-tries=5
retry-wait=15

# Speed: segmented downloads across multiple connections per server
max-concurrent-downloads=${MAX_CONCURRENT_DOWNLOADS:-5}
max-connection-per-server=${MAX_CONNECTION_PER_SERVER:-8}
split=${SPLIT:-8}
min-split-size=${MIN_SPLIT_SIZE:-4M}
disk-cache=${DISK_CACHE:-64M}

# Every connection goes through the egress gateway as a CONNECT tunnel
# (tunnel = http:// too, not just https://), so it sees and logs each one.
# This container has no other route out.
all-proxy=${ARIA2_PROXY:-http://egress:3128}
proxy-method=tunnel

# No peer-to-peer and no fan-out: a downloaded .torrent/.metalink file stays
# a plain file instead of making aria2 contact peers, trackers or mirrors.
# (The API also rejects magnet/torrent/metalink links up front.)
follow-torrent=false
follow-metalink=false
enable-dht=false
enable-dht6=false
bt-enable-lpd=false
enable-peer-exchange=false
EOF
as_user touch "$SESSION"
as_user chmod 600 "$CONF" "$SESSION"

exec su-exec "$PUID:$PGID" aria2c --conf-path="$CONF"
